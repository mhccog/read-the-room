#!/usr/bin/env python3
"""Writes overlay/watch/appearance-data.js from tools/appearance_items.json.

The JSON is the source of truth for Watch > Appearance & movement (videos, written pieces, interactives,
code/data and evidence points). Edit the JSON, run this, then run tools/build.py as usual.
Every item needs: id, fmt (video|written|interactive|code|point), stream (main|non), topics, primary (one of topics), title.
This data is used only by the hub's Watch tab. It is never read by Learn, Ask (Hughes or Blend) or the Hughes KB.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, 'appearance_items.json'), encoding='utf-8'))
ids = [x['id'] for x in d['items']]
assert len(ids) == len(set(ids)), 'duplicate ids'
FMT = {'video', 'written', 'interactive', 'code', 'point'}
for x in d['items']:
    assert x['fmt'] in FMT and x['stream'] in ('main', 'non'), x['id']
    assert x['primary'] in x['topics'], x['id']
js = ('/* Watch > Appearance & movement. Generated by tools/appearance_build.py from tools/appearance_items.json.\n'
      '   Hand-written summaries; videos play from YouTube (not re-hosted). Hub-only: never read by Learn, Ask or the Hughes KB.\n'
      '   Links last checked ' + d['checked'] + '. */\nwindow.WATCH_AP=' + json.dumps(d, ensure_ascii=False, separators=(',', ':')) + ';\n')
open(os.path.join(os.path.dirname(HERE), 'overlay/watch/appearance-data.js'), 'w', encoding='utf-8').write(js)
print(len(ids), 'items,', len(js.encode()), 'bytes')
